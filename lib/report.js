'use strict';

const fs = require('fs');
const path = require('path');
const { auditUrl } = require('./audit');

function esc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function generateReportHtml(result) {
  const failed = result.checks.filter(c => !c.pass);
  const passed = result.checks.filter(c => c.pass);

  const checkRows = result.checks.map(c => `
    <tr class="${c.pass ? 'pass' : 'fail'}">
      <td>${c.pass ? '✅' : '❌'}</td>
      <td>${esc(c.label)}</td>
      <td><span class="cat">${esc(c.category)}</span></td>
      <td>${esc(c.detail)}</td>
    </tr>`).join('');

  const fixRows = result.fixes.map(f => `
    <tr><td><span class="pri-${esc(f.priority)}">${esc(f.priority)}</span></td><td>${esc(f.check)}</td><td>${esc(f.action)}</td></tr>`).join('');

  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="UTF-8"><title>LaunchProof Report — ${esc(result.url)}</title>
<style>
  body{font-family:Inter,system-ui,sans-serif;max-width:800px;margin:0 auto;padding:2rem;color:#1a1a2e;line-height:1.6}
  h1{font-size:1.8rem} .score{font-size:3rem;font-weight:800;color:#6366f1}
  .grade{display:inline-block;padding:0.3rem 0.8rem;border-radius:6px;font-weight:700;background:#6366f122;color:#6366f1}
  table{width:100%;border-collapse:collapse;margin:1rem 0;font-size:0.9rem}
  th,td{padding:0.6rem;text-align:left;border-bottom:1px solid #eee}
  th{background:#f8f8fc;font-weight:600}
  .pass td{color:#333}.fail td{background:#fef2f2}
  .cat{font-size:0.75rem;background:#eee;padding:0.15rem 0.4rem;border-radius:4px}
  .pri-HIGH{color:#ef4444;font-weight:700}.pri-MEDIUM{color:#eab308;font-weight:600}.pri-LOW{color:#888}
  .header{border-bottom:2px solid #6366f1;padding-bottom:1rem;margin-bottom:2rem}
  .footer{margin-top:3rem;padding-top:1rem;border-top:1px solid #eee;color:#888;font-size:0.85rem}
</style></head><body>
<div class="header">
  <h1>🛡️ LaunchProof Trust Report</h1>
  <p><strong>URL:</strong> ${esc(result.url)}</p>
  <p><strong>Scanned:</strong> ${esc(result.scannedAt)}</p>
  <div class="score">${esc(result.percentage)}%</div>
  <span class="grade">Grade ${esc(result.grade)}</span>
  <p>${passed.length}/${result.checks.length} trust checks passed</p>
</div>

<h2>All Trust Checks</h2>
<table><tr><th></th><th>Check</th><th>Category</th><th>Detail</th></tr>${checkRows}</table>

<h2>Priority Fix Checklist</h2>
<table><tr><th>Priority</th><th>Issue</th><th>Recommended Action</th></tr>${fixRows}</table>

<h2>Summary</h2>
<p>${failed.length === 0 ? 'Excellent! Your landing page passes all trust checks.' :
  `Your page has <strong>${failed.length} issues</strong> that may cause crypto investors to bounce. Fix HIGH priority items first — they have the biggest impact on perceived legitimacy.`}</p>

<div class="footer">
  <p>Generated by LaunchProof · https://green-service.online</p>
  <p>Need help implementing fixes? Upgrade to Priority Review (99 USDT) for 1-on-1 consultation.</p>
</div>
</body></html>`;
}

async function fulfillOrder(orderId) {
  const ordersFile = path.join(__dirname, '..', 'data', 'orders.json');
  const orders = JSON.parse(fs.readFileSync(ordersFile, 'utf8'));
  const order = orders.find(o => o.id === orderId);
  if (!order) throw new Error('Order not found: ' + orderId);

  const result = await auditUrl(order.url);
  const html = generateReportHtml(result);
  const reportsDir = path.join(__dirname, '..', 'data', 'reports');
  fs.mkdirSync(reportsDir, { recursive: true });
  const reportPath = path.join(reportsDir, `${orderId}.html`);
  fs.writeFileSync(reportPath, html);

  order.status = 'fulfilled';
  order.reportPath = reportPath;
  order.fulfilledAt = new Date().toISOString();
  fs.writeFileSync(ordersFile, JSON.stringify(orders, null, 2));

  return { order, reportPath };
}

module.exports = { generateReportHtml, fulfillOrder };
